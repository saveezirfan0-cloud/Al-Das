"use client";

import * as React from "react";
import { Loader2, ShieldCheck } from "lucide-react";
import { useRouter } from "next/navigation";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { safeNextPath } from "@/lib/security/next-path";
import { createClient } from "@/lib/supabase/client";

import { confirmMfaEnrolled } from "../actions";

type Pending = { factorId: string; qr: string; secret: string };

/** Authenticator-app (TOTP) enrolment: scan the code, then prove it works with the first 6 digits. */
export function EnrollForm({ next }: { next?: string }) {
  const router = useRouter();
  const [pending, setPending] = React.useState<Pending | null>(null);
  const [code, setCode] = React.useState("");
  const [error, setError] = React.useState<string | null>(null);
  const [busy, setBusy] = React.useState(false);

  const start = React.useCallback(async () => {
    setBusy(true);
    setError(null);
    const supabase = createClient();
    // Half-finished enrolments (never verified) block a new one with the same name; clear them first.
    const { data: factors } = await supabase.auth.mfa.listFactors();
    for (const f of factors?.all ?? []) {
      if (f.factor_type === "totp" && f.status === "unverified")
        await supabase.auth.mfa.unenroll({ factorId: f.id });
    }
    const { data, error: enrollError } = await supabase.auth.mfa.enroll({
      factorType: "totp",
      friendlyName: `Authenticator ${new Date().toISOString().slice(0, 10)}`,
    });
    setBusy(false);
    if (enrollError || !data)
      return setError("Could not start set-up. Reload the page and try again.");
    setPending({ factorId: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
  }, []);

  React.useEffect(() => {
    void start();
  }, [start]);

  async function verify(e: React.FormEvent) {
    e.preventDefault();
    if (!pending) return;
    setBusy(true);
    setError(null);
    const supabase = createClient();
    const challenge = await supabase.auth.mfa.challenge({ factorId: pending.factorId });
    if (challenge.error) {
      setBusy(false);
      return setError("Could not start the check. Try again.");
    }
    const verified = await supabase.auth.mfa.verify({
      factorId: pending.factorId,
      challengeId: challenge.data.id,
      code: code.trim(),
    });
    if (verified.error) {
      setBusy(false);
      return setError(
        "That code is not right. Check the time on your phone and try the next code.",
      );
    }
    const res = await confirmMfaEnrolled();
    setBusy(false);
    if (!res.ok) return setError(res.error);
    router.replace(safeNextPath(next, "/"));
    router.refresh();
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <ShieldCheck className="size-5" /> Set up two-step verification
        </CardTitle>
        <CardDescription>
          Your role needs a second step at sign-in. Scan the code with an authenticator app (Google
          Authenticator, Microsoft Authenticator, 1Password, Authy), then enter the 6 digits it
          shows.
        </CardDescription>
      </CardHeader>
      <CardContent className="flex flex-col gap-4">
        {pending ? (
          <>
            <div className="flex justify-center rounded-md border bg-white p-3">
              {/* The QR code is an SVG data URI generated by Supabase Auth. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                src={pending.qr}
                alt="QR code for your authenticator app"
                width={176}
                height={176}
              />
            </div>
            <details className="text-muted-foreground text-xs">
              <summary className="cursor-pointer">Can&apos;t scan? Enter the key by hand</summary>
              <code className="bg-muted mt-2 block rounded p-2 text-xs break-all select-all">
                {pending.secret}
              </code>
            </details>
            <form onSubmit={verify} className="grid gap-3">
              <div className="grid gap-2">
                <Label htmlFor="mfa-code">6-digit code</Label>
                <Input
                  id="mfa-code"
                  inputMode="numeric"
                  autoComplete="one-time-code"
                  pattern="[0-9]{6}"
                  maxLength={6}
                  required
                  value={code}
                  onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
                />
              </div>
              {error && <p className="text-destructive text-sm">{error}</p>}
              <Button type="submit" disabled={busy || code.length !== 6}>
                {busy && <Loader2 className="animate-spin" />} Turn on two-step verification
              </Button>
            </form>
          </>
        ) : (
          <div className="text-muted-foreground flex items-center gap-2 text-sm">
            {busy ? <Loader2 className="size-4 animate-spin" /> : null}
            {error ?? "Preparing your code…"}
          </div>
        )}
        <form action="/auth/signout" method="post">
          <Button type="submit" variant="ghost" size="sm" className="w-full">
            Sign out
          </Button>
        </form>
      </CardContent>
    </Card>
  );
}
